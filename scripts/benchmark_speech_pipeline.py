#!/usr/bin/env python3
"""Benchmark the deployed Mana Piper → OpenVoice V2 HTTP path.

The default reference is generated by Mana itself, which is safe for automated
functional testing but is not a human voice-similarity acceptance test.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import threading
import time
from datetime import datetime, timezone
from pathlib import Path

import requests


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_TEXTS = (
    "سلام، این یک آزمون کوتاه برای سنجش سرعت تولید گفتار فارسی است.",
    "سامانه متارنگ باید متن را روشن، پیوسته و بدون صدای اضافه بخواند.",
    "امروز سوم نوامبر سال دو هزار و بیست و شش است و عدد چهل و دو را می‌خوانیم.",
)


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _service_health(service: str, port: int) -> dict:
    code = (
        "import json,urllib.request;"
        f"print(urllib.request.urlopen('http://127.0.0.1:{port}/health/ready',"
        "timeout=5).read().decode())"
    )
    completed = subprocess.run(
        ["docker", "compose", "exec", "-T", service, "python", "-c", code],
        cwd=ROOT,
        capture_output=True,
        text=True,
        timeout=15,
        check=False,
    )
    if completed.returncode:
        return {"status": "unavailable", "error": completed.stderr.strip()[-500:]}
    try:
        return json.loads(completed.stdout)
    except json.JSONDecodeError:
        return {"status": "invalid", "output": completed.stdout.strip()[-500:]}


class GpuSampler:
    def __init__(self) -> None:
        self.samples: list[dict[str, float | str]] = []
        self.stop_event = threading.Event()
        self.thread = threading.Thread(target=self._run, daemon=True)

    def _run(self) -> None:
        while not self.stop_event.is_set():
            completed = subprocess.run(
                [
                    "nvidia-smi",
                    "--query-gpu=name,utilization.gpu,memory.used,memory.free",
                    "--format=csv,noheader,nounits",
                ],
                capture_output=True,
                text=True,
                check=False,
            )
            if completed.returncode == 0 and completed.stdout.strip():
                name, utilization, used, free = [
                    value.strip() for value in completed.stdout.splitlines()[0].split(",")
                ]
                self.samples.append(
                    {
                        "name": name,
                        "utilization_percent": float(utilization),
                        "memory_used_mib": float(used),
                        "memory_free_mib": float(free),
                    }
                )
            self.stop_event.wait(0.2)

    def __enter__(self):
        self.thread.start()
        return self

    def __exit__(self, *_args):
        self.stop_event.set()
        self.thread.join(timeout=2)

    def summary(self) -> dict:
        if not self.samples:
            return {"samples": 0}
        return {
            "samples": len(self.samples),
            "gpu": self.samples[0]["name"],
            "max_utilization_percent": max(
                float(sample["utilization_percent"]) for sample in self.samples
            ),
            "max_memory_used_mib": max(
                float(sample["memory_used_mib"]) for sample in self.samples
            ),
            "min_memory_free_mib": min(
                float(sample["memory_free_mib"]) for sample in self.samples
            ),
        }


def _reference_audio(api_url: str, reference_path: Path | None) -> tuple[bytes, str]:
    if reference_path:
        return reference_path.read_bytes(), str(reference_path)
    response = requests.post(
        f"{api_url}/api/tts/",
        json={"text": "این صدای مرجع خودکار فقط برای آزمون فنی تبدیل صدا تولید شده است."},
        timeout=(3, 120),
    )
    response.raise_for_status()
    return response.content, "auto-generated Mana reference (functional test only)"


def _markdown(report: dict) -> str:
    tts = report["service_health"]["tts"]
    vc = report["service_health"]["vc"]
    gpu = report["gpu"]
    lines = [
        "# Speech pipeline benchmark",
        "",
        f"Generated: `{report['generated_at']}`",
        "",
        "This is an automated functional/performance benchmark. Voice similarity and",
        "Persian naturalness still require human listening approval with authorized samples.",
        "",
        "| Measurement | Result |",
        "|---|---:|",
        f"| Mana model load | {tts.get('model_load_seconds', 'n/a')} s |",
        f"| Mana cold synthesis | {tts.get('cold_synthesis_seconds', 'n/a')} s |",
        f"| OpenVoice model load | {vc.get('model_load_seconds', 'n/a')} s |",
        f"| OpenVoice recommended free VRAM | {vc.get('recommended_min_free_vram_mib', 'n/a')} MiB |",
        f"| Peak GPU utilization | {gpu.get('max_utilization_percent', 'n/a')}% |",
        f"| Peak total GPU memory used | {gpu.get('max_memory_used_mib', 'n/a')} MiB |",
        f"| Successful requests | {report['summary']['successful_requests']} |",
        f"| Failed requests | {report['summary']['failed_requests']} |",
        f"| Failure rate | {report['summary']['failure_rate']:.3f} |",
        f"| Aggregate end-to-end RTF | {report['summary']['end_to_end_rtf']} |",
        f"| First-request latency | {report['summary']['first_request_latency_seconds']} s |",
        f"| Warm average latency | {report['summary']['warm_average_latency_seconds']} s |",
        f"| Warm end-to-end RTF | {report['summary']['warm_end_to_end_rtf']} |",
        "",
        "## Requests",
        "",
        "| # | Mode | End-to-end | TTS RTF | VC RTF | VC cache hit |",
        "|---:|---|---:|---:|---:|---:|",
    ]
    for index, item in enumerate(report["requests"], 1):
        metrics = item.get("metrics", {})
        lines.append(
            f"| {index} | {item.get('mode', 'n/a')} | "
            f"{item.get('elapsed_seconds', 0):.3f} s | "
            f"{metrics.get('tts_rtf', 'n/a')} | "
            f"{metrics.get('conversion_rtf', 'n/a')} | "
            f"{metrics.get('target_cache_hit', 'n/a')} |"
        )
    lines.extend(
        [
            "",
            f"Reference: `{report['reference']}`",
            "",
            "Human quality sign-off: **not performed by this automated benchmark**.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--api-url", default="http://localhost:8000")
    parser.add_argument("--reference", type=Path)
    parser.add_argument(
        "--output-dir", type=Path, default=ROOT / "artifacts/benchmarks"
    )
    args = parser.parse_args()
    api_url = args.api_url.rstrip("/")
    reference_bytes, reference_description = _reference_audio(api_url, args.reference)

    service_health = {
        "tts": _service_health("tts", 5002),
        "vc": _service_health("vc", 5003),
    }
    results = []
    with GpuSampler() as sampler:
        for index, text in enumerate(DEFAULT_TEXTS):
            mode = "first_request" if index == 0 else "warm"
            started = time.perf_counter()
            try:
                response = requests.post(
                    f"{api_url}/api/v1/speech/jobs/",
                    data={"text": text, "tau": "0.3"},
                    files={
                        "reference_audio": ("reference.wav", reference_bytes, "audio/wav")
                    },
                    timeout=(3, 240),
                )
                elapsed = time.perf_counter() - started
                response.raise_for_status()
                payload = response.json()
                converted = requests.get(payload["converted_audio_url"], timeout=(3, 60))
                converted.raise_for_status()
                results.append(
                    {
                        "status": "success",
                        "mode": mode,
                        "text": text,
                        "elapsed_seconds": elapsed,
                        "job_id": payload["job_id"],
                        "fallback_used": payload["fallback_used"],
                        "metrics": payload["metrics"],
                        "converted_bytes": len(converted.content),
                        "converted_sha256": _sha256(converted.content),
                    }
                )
            except (requests.RequestException, ValueError) as exc:
                results.append(
                    {
                        "status": "failed",
                        "mode": mode,
                        "text": text,
                        "elapsed_seconds": time.perf_counter() - started,
                        "error": f"{type(exc).__name__}: {exc}",
                    }
                )
        gpu_summary = sampler.summary()

    successful = [item for item in results if item["status"] == "success"]
    total_audio_duration = sum(
        float(item["metrics"].get("audio_duration") or 0.0) for item in successful
    )
    total_latency = sum(float(item["elapsed_seconds"]) for item in successful)
    warm = [item for item in successful if item.get("mode") == "warm"]
    warm_latency = sum(float(item["elapsed_seconds"]) for item in warm)
    warm_audio_duration = sum(
        float(item["metrics"].get("audio_duration") or 0.0) for item in warm
    )
    first_request = next(
        (item for item in results if item.get("mode") == "first_request"), None
    )
    summary = {
        "request_count": len(results),
        "successful_requests": len(successful),
        "failed_requests": len(results) - len(successful),
        "failure_rate": (len(results) - len(successful)) / len(results) if results else 0.0,
        "total_pipeline_latency_seconds": total_latency,
        "total_audio_duration_seconds": total_audio_duration,
        "end_to_end_rtf": (
            total_latency / total_audio_duration if total_audio_duration else None
        ),
        "first_request_latency_seconds": (
            float(first_request["elapsed_seconds"]) if first_request else None
        ),
        "warm_successful_requests": len(warm),
        "warm_average_latency_seconds": warm_latency / len(warm) if warm else None,
        "warm_end_to_end_rtf": (
            warm_latency / warm_audio_duration if warm_audio_duration else None
        ),
        "warm_average_tts_rtf": (
            sum(float(item["metrics"].get("tts_rtf") or 0.0) for item in warm) / len(warm)
            if warm
            else None
        ),
        "warm_average_conversion_rtf": (
            sum(float(item["metrics"].get("conversion_rtf") or 0.0) for item in warm)
            / len(warm)
            if warm
            else None
        ),
    }

    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "api_url": api_url,
        "reference": reference_description,
        "reference_sha256": _sha256(reference_bytes),
        "automated_functional_test": True,
        "human_quality_signoff": False,
        "service_health": service_health,
        "gpu": gpu_summary,
        "summary": summary,
        "requests": results,
    }
    args.output_dir.mkdir(parents=True, exist_ok=True)
    json_path = args.output_dir / "speech-pipeline-latest.json"
    markdown_path = args.output_dir / "speech-pipeline-latest.md"
    json_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    markdown_path.write_text(_markdown(report), encoding="utf-8")
    print(json_path)
    print(markdown_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
